#!/usr/bin/env bash
#
# Collect every TradeIT benchmark into a single report.
#
# It captures: the machine environment, the in-process hot-path benchmarks (matcher,
# ring producer/consumer/end-to-end), the component micro-benchmarks (ring, WAL, ingest),
# and - when a stack is running - the end-to-end HTTP load test, the pipeline metrics and
# the Postgres row counts. Optionally it runs the recovery demo.
#
# Usage:
#   scripts/bench.sh                       # everything it can find, into benchmarks/bench-<ts>.md
#   OUT=results.md scripts/bench.sh        # choose the output file
#   E2E=no scripts/bench.sh                # skip the parts that need a running stack
#   RECOVERY=yes scripts/bench.sh          # also run the kill/restart recovery demo
#
# Tuning (env vars):
#   BENCHTIME=3x        go test -benchtime for the hot-path benchmarks
#   COUNT=3             go test -count (repetitions) for the hot-path benchmarks
#   MICRO_BENCHTIME=200ms   go test -benchtime for the component micro-benchmarks
#   BENCH_LATENCY_STRIDE=16 latency sampling stride for the hot-path benchmarks
#                           (1 = time every order, best tail resolution)
#   LOAD_N=100000 LOAD_C=128 LOAD_VERIFY=500   cmd/loadgen parameters for the E2E test
#   BASE=http://localhost:8000                user-order-service base URL
#   PROFILE=yes         also write a CPU + memory profile of the consumer benchmark
#
set -euo pipefail

cd "$(dirname "$0")/.."
ROOT="$PWD"

OUT="${OUT:-benchmarks/bench-$(date +%Y%m%d-%H%M%S).md}"
BENCHTIME="${BENCHTIME:-3x}"
COUNT="${COUNT:-3}"
MICRO_BENCHTIME="${MICRO_BENCHTIME:-200ms}"
LOAD_N="${LOAD_N:-100000}"
LOAD_C="${LOAD_C:-128}"
LOAD_VERIFY="${LOAD_VERIFY:-500}"
BASE="${BASE:-http://localhost:8000}"
E2E="${E2E:-auto}"        # auto | yes | no
RECOVERY="${RECOVERY:-no}"
PROFILE="${PROFILE:-no}"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
RAW="$TMP/all-bench.txt"
: >"$RAW"
FAILED=0

mkdir -p "$(dirname "$OUT")"
: >"$OUT"

# --- helpers ---------------------------------------------------------------------------

h()   { printf '\n## %s\n\n' "$*" >>"$OUT"; }
note(){ printf '%s\n' "$*" >>"$OUT"; }
fence(){ printf '```\n' >>"$OUT"; }

# run a benchmark command: capture combined output to the report (fenced) and to RAW.
# A non-zero exit is recorded and reported at the end rather than swallowed.
run() {
  local title="$1"; shift
  h "$title"
  fence
  printf '$ %s\n' "$*" >>"$OUT"
  local rc=0
  "$@" >"$TMP/run.out" 2>&1 || rc=$?
  tee -a "$OUT" "$RAW" <"$TMP/run.out" >/dev/null
  fence
  if [ "$rc" -ne 0 ]; then
    note "_Command exited with status $rc._"
    say "WARNING: '$title' exited with status $rc"
    FAILED=1
  fi
}

# metric_filter prints the headline metric names to scrape for a service. Every service
# registers the whole metric set, so most series are zero elsewhere; keep only the ones
# that matter and drop the histogram buckets.
metric_filter() {
  case "$1" in
    user-order) echo 'tradeit_(orders_submitted_total|ring_full_total|wal_sync_seconds_(count|sum)|http_requests_total|cache_errors_total)' ;;
    engine)     echo 'tradeit_(commands_applied_total|consumer_watermark|ring_pending|http_requests_total)' ;;
    projection) echo 'tradeit_(records_projected_total|trades_projected_total|projection_seq|projection_flush_seconds_(count|sum)|projection_errors_total|cache_errors_total)' ;;
    *)          echo '^tradeit_' ;;
  esac
}

say() { printf '\n==> %s\n' "$*"; }

# --- header ----------------------------------------------------------------------------

cat >>"$OUT" <<EOF
# TradeIT benchmark report

Generated by \`scripts/bench.sh\` on $(date -u +%Y-%m-%dT%H:%M:%SZ).

EOF

h "Environment"
{
  echo "- Date (UTC): $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "- Host: $(hostname)"
  echo "- Kernel: $(uname -srmo)"
  echo "- CPU: $(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2- | sed 's/^ //')"
  echo "- Threads: $(nproc)"
  echo "- Memory: $(awk '/MemTotal/ {printf "%.1f GiB", $2/1024/1024}' /proc/meminfo)"
  echo "- Go: $(go version)"
  echo "- GOMAXPROCS: ${GOMAXPROCS:-default ($(nproc))}"
  if [ -r /sys/devices/system/cpu/cpu0/cpufreq/scaling_governor ]; then
    echo "- CPU governor: $(cat /sys/devices/system/cpu/cpu0/cpufreq/scaling_governor)"
  fi
  echo "- Benchmark dir: $([ -d /dev/shm ] && echo '/dev/shm (tmpfs)' || echo 'temp dir')"
  echo "- Working tree: $(git rev-parse --short HEAD 2>/dev/null || echo 'n/a')"
} >>"$OUT"

# --- 1. in-process hot path ------------------------------------------------------------

say "in-process hot-path benchmarks"
run "Hot path: matcher, ring producer/consumer, end-to-end" \
  go test -run '^$' -bench 'BenchmarkMatcherProductionLike|BenchmarkRing' \
  -benchtime "$BENCHTIME" -count "$COUNT" ./internal/benchmark/

# --- 2. component micro-benchmarks -----------------------------------------------------

say "component micro-benchmarks"
run "Components: shared-memory ring, WAL, ingest producer" \
  go test -run '^$' -bench . -benchtime "$MICRO_BENCHTIME" -count "$COUNT" \
  ./internal/shmring/ ./internal/wal/ ./internal/ingest/

# --- 3. optional profiles --------------------------------------------------------------

if [ "$PROFILE" = "yes" ]; then
  say "capturing CPU and memory profiles of the consumer benchmark"
  go test -run '^$' -bench BenchmarkRingConsumerOnly -benchtime 5x \
    -cpuprofile "$TMP/consumer.cpu" -memprofile "$TMP/consumer.mem" ./internal/benchmark/ >/dev/null 2>&1 || true
  if [ -f "$TMP/consumer.cpu" ]; then
    h "Consumer CPU profile (top)"
    fence
    go tool pprof -top -nodecount=20 "$TMP/consumer.cpu" 2>/dev/null | tee -a "$OUT" >/dev/null || true
    fence
    h "Consumer allocation profile (top)"
    fence
    go tool pprof -alloc_objects -top -nodecount=20 "$TMP/consumer.mem" 2>/dev/null | tee -a "$OUT" >/dev/null || true
    fence
  fi
fi

# --- 4. end-to-end (needs a running stack) ---------------------------------------------

stack_up() { curl -fsS -m 2 "$BASE/healthz" >/dev/null 2>&1; }

do_e2e=no
case "$E2E" in
  yes) do_e2e=yes ;;
  auto) stack_up && do_e2e=yes ;;
  no) do_e2e=no ;;
esac

if [ "$do_e2e" = "yes" ]; then
  say "end-to-end load test against $BASE"
  go build -o "$TMP/loadgen" ./cmd/loadgen
  run "End-to-end: ${LOAD_N} orders @ concurrency ${LOAD_C}" \
    "$TMP/loadgen" -base "$BASE" -n "$LOAD_N" -c "$LOAD_C" -verify "$LOAD_VERIFY" -verify-timeout 60s

  h "Pipeline metrics"
  for pair in "user-order:8000" "engine:8001" "projection:8002"; do
    name="${pair%%:*}"; port="${pair##*:}"
    fence
    printf '# %s (%s)\n' "$name" "$port" >>"$OUT"
    curl -fsS -m 5 "http://localhost:$port/metrics" 2>/dev/null | grep -E "$(metric_filter "$name")" >>"$OUT" || echo "(unreachable)" >>"$OUT"
    fence
  done

  if command -v docker >/dev/null 2>&1 && docker compose ps >/dev/null 2>&1; then
    h "Postgres row counts"
    fence
    printf '$ docker compose exec -T db psql ...\n' >>"$OUT"
    docker compose exec -T db psql -U postgres -d tradeit \
      -c "select (select count(*) from orders) as orders, (select count(*) from trade_details) as trades;" \
      >>"$OUT" 2>&1 || echo "(unavailable)" >>"$OUT"
    docker compose exec -T db psql -U postgres -d tradeit \
      -c 'select symbol_id, seq, log_offset from projection_checkpoints;' \
      >>"$OUT" 2>&1 || true
    fence
  fi
else
  h "End-to-end load test"
  note "Skipped (no stack at $BASE; set E2E=yes or start the stack with"
  note "\`docker compose up -d --build\`). The in-process benchmarks above need no stack."
fi

# --- 5. optional recovery demo ---------------------------------------------------------

if [ "$RECOVERY" = "yes" ]; then
  if [ "$do_e2e" = "yes" ] && command -v docker >/dev/null 2>&1; then
    say "recovery demo (kill -9 the engine mid-load)"
    run "Recovery: kill -9 + restart the engine under load" \
      bash scripts/recovery.sh "$LOAD_N" "$LOAD_C"
  else
    h "Recovery demo"
    note "Skipped (needs a running stack and docker; set E2E=yes RECOVERY=yes)."
  fi
fi

# --- 6. combined results ---------------------------------------------------------------

h "Medians (per benchmark, across the -count runs)"
note "Median ns/op for every benchmark, and median orders/sec where the benchmark reports it."
fence
{
  awk '/^Benchmark/ { name=$1; sub(/-[0-9]+$/, "", name); print name, $3 }' "$RAW" \
    | sort -k1,1 -k2,2n \
    | awk '
      function flush() {
        if (n == 0) return
        med = (n % 2 == 1) ? v[(n+1)/2] : (v[n/2] + v[n/2+1]) / 2
        printf "%-38s %12.2f ns/op   (n=%d)\n", cur, med, n
      }
      $1 != cur { flush(); cur = $1; n = 0 }
      { v[++n] = $2 }
      END { flush() }
    '
  awk '/orders\/sec/ { name=$1; sub(/-[0-9]+$/, "", name); for (i=1;i<=NF;i++) if ($i=="orders/sec") print name, $(i-1) }' "$RAW" \
    | sort -k1,1 -k2,2n \
    | awk '
      function flush() {
        if (n == 0) return
        med = (n % 2 == 1) ? v[(n+1)/2] : (v[n/2] + v[n/2+1]) / 2
        printf "%-38s %12.0f orders/sec   (n=%d)\n", cur, med, n
      }
      $1 != cur { flush(); cur = $1; n = 0 }
      { v[++n] = $2 }
      END { flush() }
    '
} >>"$OUT"
fence

h "Latency (sampled, median across the -count runs)"
note "Per-operation latency percentiles reported by the in-process benchmarks. \`/order\` is"
note "per matching command; \`/batch\` is per producer submission batch (512 orders)."
note "Sampling stride is ${BENCH_LATENCY_STRIDE:-16} (set BENCH_LATENCY_STRIDE=1 to time every operation)."
fence
awk '
  /^Benchmark/ {
    name=$1; sub(/-[0-9]+$/, "", name)
    for (i=2;i<=NF;i++) {
      if ($i ~ /^(mean|p50|p90|p99|p999|max)-ns\/(order|batch)$/) print name, $i, $(i-1)
    }
  }
' "$RAW" \
  | sort -k1,1 -k2,2 -k3,3n \
  | awk '
    function flush() {
      if (n == 0) return
      med = (n % 2 == 1) ? v[(n+1)/2] : (v[n/2] + v[n/2+1]) / 2
      printf "%-38s %-16s %12.1f ns   (n=%d)\n", curName, curMetric, med, n
    }
    {
      name=$1; metric=$2; val=$3+0
      if (name != curName || metric != curMetric) { flush(); curName=name; curMetric=metric; n=0 }
      v[++n]=val
    }
    END { flush() }
  ' >>"$OUT"
fence


h "Combined benchmark result lines"
fence
grep -E '^(Benchmark|PASS|FAIL|ok )' "$RAW" >>"$OUT" 2>/dev/null || true
fence

h "How to read this"
cat >>"$OUT" <<'EOF'
- `orders/sec` comes from the benchmark's reported metric; `ns/op` and `allocs/op` are the
  standard Go values. Take the median of the `-count` repetitions.
- `p50-ns/order` etc. are per-operation latencies sampled by the in-process benchmarks
  (default: one in 16 operations, `BENCH_LATENCY_STRIDE`). `/batch` is per producer
  submission batch (512 orders). Sampling keeps the clock reads off the throughput path;
  set `BENCH_LATENCY_STRIDE=1` for a latency-focused run.
- The hot-path benchmarks run on tmpfs (`/dev/shm`), so the WAL fsync is not a confound;
  the producer/consumer numbers are the ring + group-commit path.
- The end-to-end numbers include the HTTP client (same host by default), so they measure
  the front door, not the engine. For the engine, read the hot-path section.
- Compare runs only on the same SKU/region and with the same `GOMAXPROCS` (reported above),
  and check `current_clocksource = tsc` before trusting any ns figure.
EOF

say "report written to $OUT"
if [ "$FAILED" -ne 0 ]; then
  say "one or more benchmark commands failed; see the report"
  exit 1
fi
printf '\n'
